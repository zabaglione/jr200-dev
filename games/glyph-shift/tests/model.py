def move(pos, action):
    if action == 1 and pos >= 8:
        return pos - 8
    if action == 2 and pos < 56:
        return pos + 8
    if action == 3 and pos % 8:
        return pos - 1
    if action == 4 and pos % 8 < 7:
        return pos + 1
    return pos


class GlyphShift:
    port = None

    def __init__(self):
        self.reset()

    def reset(self):
        for name in FIELDS:
            setattr(self, name, 0)
        self.b = [0] * 64
        self.d = [0] * 70
        self.frames = 0

    def init(self):
        self.d = list(LEVELS_DATA[self.port.level])
        self.facing = 2
        self.b = self.d[:64]
        self.pos = self.origin = self.d[64]
        self.par = self.d[69]

    def spend_move(self):
        if self.moves < 255:
            self.moves += 1
        else:
            self.overflow = 1

    def take_rune(self, pos):
        if pos == self.d[67]:
            self.runes |= 1
        if pos == self.d[68]:
            self.runes |= 2

    def act(self, action):
        self.frames = 0
        if action < 5:
            self.facing = action
        if action == 5:
            self.phase ^= 1
            if self.changes < 255:
                self.changes += 1
            self.spend_move()
        if action < 5:
            n = move(self.pos, action)
            cell = self.b[n]
            if (n != self.pos and cell != 1 and not (cell == 4 and self.phase == 0)
                    and not (cell == 5 and self.phase == 1)):
                self.pos = self.origin = n
                self.frames += 2
                self.spend_move()
                self.take_rune(self.pos)
        if self.b[self.pos] == 3:
            self.port.rank_clear()

    def state_bytes(self):
        return bytes([getattr(self, n) for n in FIELDS] + self.b).hex()
