; One-shot success/failure phrases; duration zero ends a phrase.
END_FEEDBACK:
    LDAA [G_MODE]
    CMPA 8
    BCS END_SOUND_DONE
    TST [G_CLEAR_SUNG]
    BNE END_SOUND_DONE
    INC [G_CLEAR_SUNG]
    LDX END_NOTES
    CMPA 9
    BEQ PLAY_PHRASE
    LDX FAIL_NOTES
PLAY_PHRASE:
    STX [SOUND_PTR]
END_SOUND_NOTE:
    LDX [SOUND_PTR]
    LDAB [X + 2]
    BEQ END_SOUND_DONE_PLAYING
    STAB [SOUND_DURATION]
    LDAA [X + 1]
    JSR jr_sound_c_start
END_SOUND_DURATION:
    LDX 0x0200
END_SOUND_WAIT:
    DEX
    BNE END_SOUND_WAIT
    DEC [SOUND_DURATION]
    BNE END_SOUND_DURATION
    JSR jr_sound_c_stop
    LDX [SOUND_PTR]
    ADDX8 3
    STX [SOUND_PTR]
    BRA END_SOUND_NOTE
END_SOUND_DONE_PLAYING:
    JSR jr_sound_c_stop
    JSR POLL_KEY
    CLR [G_PENDING]
END_SOUND_DONE:
    RTS
END_NOTES:
    .db 0x06,0xAB,3, 0x05,0x4C,3, 0x04,0x74,4
    .db 0x03,0x57,3, 0x04,0x74,3, 0x03,0x57,10
END_NOTES_END:
    .db 0,0,0
FAIL_NOTES:
