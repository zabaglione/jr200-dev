MENU_INPUT:
    LDAA [G_KEY]
    CMPA 6
    BEQ MENU_BACK
    LDAA [G_MODE]
    CMPA 6
    BEQ MENU_HELP_CLOSE
    LDAA [G_KEY]
    CMPA 1
    BEQ MENU_UP
    CMPA 2
    BEQ MENU_DOWN
    CMPA 5
    BEQ MENU_CONFIRM
    RTS
MENU_UP:
MENU_DOWN:
    LDAA [G_MODE]
    CMPA 3
    BEQ BAG_LIMIT
    CMPA 4
    BEQ ITEM_LIMIT
    LDAA [G_CONTEXT]
    ADDA 6
    BRA MENU_LIMIT
BAG_LIMIT:
    LDAA 6
    BRA MENU_LIMIT
ITEM_LIMIT:
    LDAA 2
MENU_LIMIT:
    TAB
    LDAA [G_MENU]
    JSR WRAP_CURSOR
    STAA [G_MENU]
MENU_INPUT_DONE:
    RTS
; A=current index, B=last index, G_KEY=up/down. Shared by every list.
WRAP_CURSOR:
    STAB [TEMP]
    LDAB [G_KEY]
    DECB
    BEQ WRAP_UP
    INCA
    CMPA [TEMP]
    BLS WRAP_DONE
    CLRA
    RTS
WRAP_UP:
    TSTA
    BNE WRAP_DECREMENT
    LDAA [TEMP]
    RTS
WRAP_DECREMENT:
    DECA
WRAP_DONE:
    RTS
MENU_BACK:
    LDAA [G_MODE]
    CMPA 4
    BNE LONG_U45
    JMP MENU_TO_BAG
LONG_U45:
    CMPA 3
    BNE FAR_UI_26_0
    JMP MENU_TO_MAIN
FAR_UI_26_0:
    CMPA 6
    BNE FAR_UI_26_1
    JMP MENU_TO_MAIN
FAR_UI_26_1:
    LDAA 1
    STAA [G_MODE]
    RTS
MENU_TO_BAG:
    LDAA 3
    STAA [G_MODE]
    LDAA [G_SLOT]
    STAA [G_MENU]
    RTS
MENU_HELP_CLOSE:
    LDAA [G_KEY]
    CMPA 5
    BNE MENU_INPUT_DONE
MENU_TO_MAIN:
    LDAA 2
    STAA [G_MODE]
    CLR [G_MENU]
    RTS
MENU_CONFIRM:
    LDAA [G_MODE]
    CMPA 3
    BEQ BAG_CONFIRM
    CMPA 4
    BNE FAR_UI_14_0
    JMP ITEM_CONFIRM
FAR_UI_14_0:
    LDAA [G_MENU]
    TST [G_CONTEXT]
    BEQ MAIN_CHOICE
    TSTA
    BNE MAIN_HAS_STAIRS
    JMP STAIRS_ACTION
MAIN_HAS_STAIRS:
    DECA
MAIN_CHOICE:
    TSTA
    BEQ OPEN_BAG
    CMPA 1
    BEQ CHOOSE_WAIT
    CMPA 2
    BEQ CHOOSE_NORMAL_INSPECT
    CMPA 3
    BEQ CHOOSE_SUSPEND
    CMPA 4
    BEQ CHOOSE_HELP
    CMPA 5
    BEQ CHOOSE_SEARCH
    JMP MENU_BACK
CHOOSE_HELP:
    LDAA 6
    STAA [G_MODE]
    RTS
CHOOSE_SEARCH:
    LDAA 1
    STAA [G_MODE]
    JMP SEARCH_ACTION
OPEN_BAG:
    LDAA 3
    STAA [G_MODE]
    CLR [G_MENU]
    RTS
CHOOSE_WAIT:
    LDAA 1
    STAA [G_MODE]
    CLR [G_MESSAGE]
    JMP COMMIT_TURN
CHOOSE_NORMAL_INSPECT:
    CLR [G_WAND_SLOT]
CHOOSE_INSPECT:
    LDAA 5
    STAA [G_MODE]
    LDAA [G_X]
    STAA [G_INSPECT_X]
    LDAA [G_Y]
    STAA [G_INSPECT_Y]
    RTS
CHOOSE_SUSPEND:
    LDAA 7
    STAA [G_MODE]
    LDAA 1
    STAA [G_SUSPEND]
    RTS
BAG_CONFIRM:
    LDAA [G_MENU]
    CMPA 6
    BNE FAR_UI_26_2
    JMP MENU_TO_MAIN
FAR_UI_26_2:
    LDAA [G_MENU]
    STAA [G_SLOT]
    JSR BAG_ITEM
    TSTA
    BEQ BAG_CONFIRM_DONE
    LDAA 4
    STAA [G_MODE]
    CLR [G_MENU]
BAG_CONFIRM_DONE:
    RTS
ITEM_CONFIRM:
    LDAA [G_MENU]
    BEQ ITEM_USE
    CMPA 1
    BEQ LONG_U133
    JMP MENU_TO_BAG
LONG_U133:
    JMP DISCARD_ITEM
ITEM_USE:
    JMP USE_ITEM
INSPECT_MOVE:
    LDAA [G_KEY]
    CMPA 5
    BNE INSPECT_NOT_CONFIRM
    JMP INSPECT_CONFIRM
INSPECT_NOT_CONFIRM:
    CMPA 6
    BEQ INSPECT_CLOSE
    CMPA 11
    BEQ INSPECT_DONE
    LDAA [G_INSPECT_X]
    LDAB [G_KEY]
    DECB
    LDX DIRECTION_DX
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    ADDA [X]
    CMPA MAP_WIDTH
    BCC INSPECT_DONE
    STAA [NX]
    LDAA [G_INSPECT_Y]
    LDX DIRECTION_DY
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    ADDA [X]
    CMPA MAP_HEIGHT
    BCC INSPECT_DONE
    STAA [NY]
    TAB
    LDAA [NX]
    JSR VISIBLE_CELL
    TST [X]
    BEQ INSPECT_DONE
    LDAA [NX]
    STAA [G_INSPECT_X]
    LDAA [NY]
    STAA [G_INSPECT_Y]
INSPECT_DONE:
    RTS
