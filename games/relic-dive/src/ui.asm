    CLR [G_WAND_SLOT]
    LDAA 1
    STAA [G_MODE]
    RTS
RENDER_SCREEN:
    JSR RENDER_FRAME
    JMP PRESENT
RENDER_FRAME:
    JSR SELECT_PCG_BANK
    JSR CLEAR
    LDAA [G_MODE]
    BEQ RENDER_TITLE
    CMPA 8
    BCS LONG_U179
    JMP RENDER_END
LONG_U179:
    CMPA 7
    BNE FAR_UI_200
    JMP RENDER_SUSPEND
FAR_UI_200:
    CMPA 6
    BNE FAR_UI_208
    JMP RENDER_HELP
FAR_UI_208:
    CMPA 2
    BEQ RENDER_MENU_JUMP
    CMPA 3
    BEQ RENDER_BAG_JUMP
    CMPA 4
    BEQ RENDER_ITEM_JUMP
    JSR RENDER_HUD
    JSR RENDER_MAP
    LDAA [G_MODE]
    CMPA 5
    BNE RENDER_MESSAGE
    JMP RENDER_INSPECT
RENDER_MESSAGE:
    LDAB [G_MESSAGE]
    ASLB
    LDX MESSAGES
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    JSR LOAD_STRING
    LDAB ((FRAMEBUFFER + 704) & 255)
    LDAA ((FRAMEBUFFER + 704) >> 8)
    JSR TEXT
    RTS
RENDER_MENU_JUMP:
    JMP RENDER_MENU
RENDER_BAG_JUMP:
    JMP RENDER_BAG
RENDER_ITEM_JUMP:
    JMP RENDER_ITEM
RENDER_TITLE:
    JSR DRAW_TITLE_ART
    LDX S_GOAL
    LDAB ((FRAMEBUFFER + 549) & 255)
    LDAA ((FRAMEBUFFER + 549) >> 8)
    JSR TEXT
    LDAA [G_DIFFICULTY]
    STAA [G_MENU]
    LDX DIFFICULTY_NAMES
    STX [UI_PTR]
    LDAA 3
    STAA [COUNT]
    LDAA 9
    STAA [UI_ROW]
    JSR RENDER_CHOICES
    LDX S_KEYS
    LDAB ((FRAMEBUFFER + 736) & 255)
    LDAA ((FRAMEBUFFER + 736) >> 8)
    JMP TEXT
; The bank is switched only at title/game transitions, never per terrain cell.
SELECT_PCG_BANK:
    LDAA 2
    LDX TILES
    LDAB TILES_END - TILES
    TST [G_MODE]
    BNE SELECT_BANK_READY
    LDAA 1
    LDX TITLE_TILES
    LDAB ((TITLE_TILES_END - TITLE_TILES) & 255)
SELECT_BANK_READY:
    CMPA [PCG_BANK]
    BEQ SELECT_BANK_DONE
    STAA [PCG_BANK]
    STX [TEXT_SRC]
    LDX JR200_PCG_BANK1
    STX [TEXT_DEST]
    JMP COPY_BYTES
SELECT_BANK_DONE:
    RTS
; High bytes are PCG; 1..126 skip blanks; 127 repeats (count, code); zero ends.
DRAW_TITLE_ART:
    LDX FRAMEBUFFER
    STX [TEXT_DEST]
    LDX TITLE_ART
TITLE_ART_NEXT:
    LDAA [X]
    BEQ TITLE_ART_DONE
    INX
    CMPA 127
    BEQ TITLE_ART_RUN
    STX [TEXT_SRC]
    TSTA
    BMI TITLE_ART_PIXEL
    TAB
    CLRA
    ADDB [TEXT_DEST + 1]
    ADCA [TEXT_DEST]
    STAB [TEXT_DEST + 1]
    STAA [TEXT_DEST]
    BRA TITLE_ART_ADVANCE
TITLE_ART_PIXEL:
    LDX [TEXT_DEST]
    STAA [X]
    INX
    STX [TEXT_DEST]
TITLE_ART_ADVANCE:
    LDX [TEXT_SRC]
    BRA TITLE_ART_NEXT
TITLE_ART_DONE:
    RTS
TITLE_ART_RUN:
    LDAB [X]
    LDAA [X + 1]
    INX
    INX
    STX [TEXT_SRC]
    LDX [TEXT_DEST]
TITLE_ART_REPEAT:
    STAA [X]
    INX
    DECB
    BNE TITLE_ART_REPEAT
    STX [TEXT_DEST]
    BRA TITLE_ART_ADVANCE
; Change one sparkle character every 256 title polls without redrawing VRAM.
TITLE_SHIMMER:
    TST [G_SEED + 1]
    BNE TITLE_SHIMMER_DONE
    LDX TITLE_SPARK_FRAMES
    LDAA [G_SEED]
    BITA 1
    BEQ TITLE_SPARK_READY
    ADDX8 8
TITLE_SPARK_READY:
    STX [TEXT_SRC]
    LDX TITLE_SPARK_ADDRESS
    STX [TEXT_DEST]
    LDAB 8
    JMP COPY_BYTES
TITLE_SHIMMER_DONE:
    RTS
RENDER_SUSPEND:
    LDX S_SUSPENDED
    LDAB ((FRAMEBUFFER + 138) & 255)
    LDAA ((FRAMEBUFFER + 138) >> 8)
    JSR TEXT
    LDX S_RESUME
    LDAB ((FRAMEBUFFER + 261) & 255)
    LDAA ((FRAMEBUFFER + 261) >> 8)
    JMP TEXT
RENDER_HELP:
    LDX HELP_LINES
    STX [UI_PTR]
    LDAA 7
    STAA [COUNT]
    LDAA 1
    STAA [UI_ROW]
    JSR RENDER_LINES
    LDX S_BACK
    LDAB ((FRAMEBUFFER + 736) & 255)
    LDAA ((FRAMEBUFFER + 736) >> 8)
    JMP TEXT
RENDER_END:
    LDX S_DEAD
    LDAA [G_MODE]
    CMPA 8
    BEQ RENDER_END_TITLE
    LDX S_WON
RENDER_END_TITLE:
    LDAB ((FRAMEBUFFER + 135) & 255)
    LDAA ((FRAMEBUFFER + 135) >> 8)
    JSR TEXT
    LDX S_END
    LDAB ((FRAMEBUFFER + 262) & 255)
    LDAA ((FRAMEBUFFER + 262) >> 8)
    JSR TEXT
    LDX S_GOLD
    LDAB ((FRAMEBUFFER + 394) & 255)
    LDAA ((FRAMEBUFFER + 394) >> 8)
    JSR TEXT
    LDX FRAMEBUFFER + 399
    JSR RENDER_GOLD
    TST [G_MESSAGE]
    BEQ END_WITHOUT_CAUSE
    JSR RENDER_MESSAGE
END_WITHOUT_CAUSE:
    JMP RENDER_HUD
RENDER_HUD:
    LDX S_FLOOR
    LDAB ((FRAMEBUFFER + 0) & 255)
    LDAA ((FRAMEBUFFER + 0) >> 8)
    JSR TEXT
    LDAA [G_FLOOR]
    INCA
    LDX FRAMEBUFFER + 1
    JSR NUMBER
    LDX S_HP
    LDAB ((FRAMEBUFFER + 5) & 255)
    LDAA ((FRAMEBUFFER + 5) >> 8)
    JSR TEXT
    LDAA [G_HP]
    LDX FRAMEBUFFER + 8
    JSR NUMBER
    LDAA 47
    LDX FRAMEBUFFER + 11
    JSR GLYPH
    LDAA [G_MAX_HP]
    LDX FRAMEBUFFER + 12
    JSR NUMBER
    LDX S_FOOD
    LDAB ((FRAMEBUFFER + 17) & 255)
    LDAA ((FRAMEBUFFER + 17) >> 8)
    JSR TEXT
    LDAA [G_FOOD]
    LDX FRAMEBUFFER + 20
    JSR NUMBER
    LDX S_LEVEL
    LDAB ((FRAMEBUFFER + 26) & 255)
    LDAA ((FRAMEBUFFER + 26) >> 8)
    JSR TEXT
    LDAA [G_LEVEL]
