    LDAA [G_ATTACK]
    LDX FRAMEBUFFER + 36
    JSR NUMBER
    LDAA [G_DEFENSE]
    LDX FRAMEBUFFER + 44
    JSR NUMBER
    LDX FRAMEBUFFER + 55
    JMP RENDER_GOLD
