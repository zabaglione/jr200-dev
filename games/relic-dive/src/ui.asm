RENDER_MAP:
    JSR POLL_KEY
    LDAA [G_MODE]
    CMPA 5
    BNE VIEW_PLAYER_XY
    LDAA [G_INSPECT_X]
    LDAB [G_INSPECT_Y]
    BRA VIEW_CALCULATE
VIEW_PLAYER_XY:
    LDAA [G_X]
    LDAB [G_Y]
VIEW_CALCULATE:
    SUBA 16
    BCC VIEW_X_POSITIVE
    CLRA
VIEW_X_POSITIVE:
    CMPA MAP_WIDTH - 32
    BLS VIEW_X_READY
    LDAA MAP_WIDTH - 32
VIEW_X_READY:
    STAA [VIEW_X]
    TBA
    SUBA 10
    BCC VIEW_Y_POSITIVE
    CLRA
VIEW_Y_POSITIVE:
    CMPA MAP_HEIGHT - 20
    BLS VIEW_Y_READY
    LDAA MAP_HEIGHT - 20
VIEW_Y_READY:
    STAA [VIEW_Y]
    STAA [ROW]
    LDX FRAMEBUFFER + 64
    STX [DRAW]
MAP_ROW:
    LDAA [VIEW_X]
    STAA [COL]
    LDAB [ROW]
    JSR CELL
    LDAB 32
; Decode sequential nibbles/bits; initialize their addresses once per row.
MAP_COLUMN:
    LDX [CELL_BIT_PTR]
    LDAA [X]
    BITA [CELL_MASK]
    BEQ TILE_UNKNOWN
    LDX [CELL_PACKED]
    LDAA [COL]
    BITA 1
    BEQ MAP_LOAD_LOW
    LDAA [X]
    LSRA
    LSRA
    LSRA
    LSRA
    BRA MAP_LOW_NIBBLE
MAP_LOAD_LOW:
    LDAA [X]
MAP_LOW_NIBBLE:
    ANDA 15
    CMPA 5
    BEQ TILE_WALL
    CMPA 6
    BCS TILE_NORMAL
    CMPA 8
    BCS TILE_FLOOR
    LDAA 25
    BRA TILE_READY
TILE_WALL:
    CLRA
    BRA TILE_NORMAL
TILE_FLOOR:
    LDAA 1
TILE_NORMAL:
    INCA
    BRA TILE_READY
TILE_UNKNOWN:
    TSTA
    BNE TILE_SINGLE_UNKNOWN
    LDAA 128
    LDX [DRAW]
MAP_BLANK_RUN:
    STAA [X]
    INX
    INC [COL]
    DECB
    BEQ MAP_BLANK_ROW_DONE
    ASL [CELL_MASK]
    BNE MAP_BLANK_RUN
    STX [DRAW]
    STAB [COUNT]
    LDAA [COL]
    LDAB [ROW]
    JSR CELL
    LDAB [COUNT]
    JMP MAP_COLUMN
MAP_BLANK_ROW_DONE:
    STX [DRAW]
    JMP MAP_NEXT_ROW
TILE_SINGLE_UNKNOWN:
    CLRA
TILE_READY:
    ORAA 128
    LDX [DRAW]
    STAA [X]
    INX
    STX [DRAW]
    ASL [CELL_MASK]
    BNE MAP_NEXT_MASK
    INC [CELL_BIT_PTR + 1]
    LDAA 1
    STAA [CELL_MASK]
; Aligned terrain/bit rows cross a page only after their last column.
MAP_NEXT_MASK:
    INC [COL]
    LDAA [COL]
    BITA 1
    BNE MAP_NEXT_PACKED
    INC [CELL_PACKED + 1]
MAP_NEXT_PACKED:
    DECB
    BEQ MAP_NEXT_ROW
    JMP MAP_COLUMN
MAP_NEXT_ROW:
    INC [ROW]
    LDAA [ROW]
    SUBA [VIEW_Y]
    CMPA 20
    BEQ MAP_TERRAIN_DONE
    JMP MAP_ROW
MAP_TERRAIN_DONE:
    LDX FLOORS + ITEM_START
    STX [ITEM_PTR]
MAP_ITEMS:
    LDX [ITEM_PTR]
    TST [X + 2]
    BEQ MAP_ITEM_NEXT
    LDAA [X]
    STAA [NX]
    LDAA [X + 1]
    STAA [NY]
    LDAA [X + 2]
    CMPA 17
    BCS MAP_OLD_ITEM
    LDAA 29
    LDAB [X + 2]
    CMPB 21
    BCS MAP_TOOL_TILE
    INCA
MAP_TOOL_TILE:
    JMP MAP_ITEM_TILE
MAP_OLD_ITEM:
    CMPA 14
    BEQ ITEM_POTION_TILE
    BHI ITEM_NEW_SCROLL_TILE
    CMPA 7
    BCS ITEM_CONSUMABLE_TILE
    CMPA 10
    BCS ITEM_WEAPON_TILE
    CMPA 13
    BCS ITEM_ARMOR_TILE
    LDAA 12
    BRA MAP_ITEM_TILE
ITEM_WEAPON_TILE:
    LDAA 10
    BRA MAP_ITEM_TILE
ITEM_ARMOR_TILE:
    LDAA 11
    BRA MAP_ITEM_TILE
ITEM_NEW_SCROLL_TILE:
    LDAA 9
    BRA MAP_ITEM_TILE
ITEM_CONSUMABLE_TILE:
    CMPA 1
    BEQ ITEM_FOOD_TILE
    CMPA 5
    BCS ITEM_POTION_TILE
    LDAA 9
    BRA MAP_ITEM_TILE
ITEM_FOOD_TILE:
    LDAA 7
    BRA MAP_ITEM_TILE
ITEM_POTION_TILE:
    LDAA 8
MAP_ITEM_TILE:
    STAA [TILE]
    JSR OVERLAY_VISIBLE
MAP_ITEM_NEXT:
    LDX [ITEM_PTR]
    ADDX8 3
    STX [ITEM_PTR]
    CPX FLOORS + FLOOR_DATA_END
    BEQ FAR_UI_900
    JMP MAP_ITEMS
FAR_UI_900:
    CLR [E_INDEX]
MAP_ENEMIES:
    JSR ENEMY_POINTER
    TST [X + 3]
    BEQ MAP_ENEMY_NEXT
    LDAA [X]
    STAA [NX]
    LDAA [X + 1]
    STAA [NY]
    LDAA [X + 2]
    CMPA 13
    BCS ENEMY_TILE_OLD
    INCA
ENEMY_TILE_OLD:
    ADDA 12
    STAA [TILE]
    JSR OVERLAY_VISIBLE
MAP_ENEMY_NEXT:
    INC [E_INDEX]
    LDAA [E_INDEX]
    CMPA MAX_ENEMIES
    BNE MAP_ENEMIES
    LDAA [G_X]
    STAA [NX]
    LDAA [G_Y]
    STAA [NY]
    JSR TILE_DESTINATION
    LDAA 6
    JSR DRAW_TILE
    RTS
OVERLAY_VISIBLE:
    LDAA [NX]
    SUBA [VIEW_X]
    CMPA 32
    BCC OVERLAY_DONE
    LDAA [NY]
    SUBA [VIEW_Y]
    CMPA 20
    BCC OVERLAY_DONE
    LDAA [NX]
    LDAB [NY]
    JSR VISIBLE_CELL
    TST [X]
    BEQ OVERLAY_DONE
    JSR TILE_DESTINATION
    LDAA [TILE]
    JSR DRAW_TILE
OVERLAY_DONE:
    RTS
TILE_DESTINATION:
    LDAA [NY]
    SUBA [VIEW_Y]
    ADDA 2
    LDAB 32
    JSR MULTIPLY
    ADDB ((FRAMEBUFFER) & 255)
    ADCA ((FRAMEBUFFER) >> 8)
    STAB [DRAW + 1]
    STAA [DRAW]
    LDAA [NX]
    SUBA [VIEW_X]
    ADDA [DRAW + 1]
    STAA [DRAW + 1]
    BCC TILE_DESTINATION_DONE
    INC [DRAW]
TILE_DESTINATION_DONE:
    RTS
DRAW_TILE:
    ORAA 128
    LDX [DRAW]
    STAA [X]
    INX
    STX [DRAW]
    RTS
LOAD_STRING:
    LDX [X]
    RTS
RENDER_MENU:
    JSR RENDER_STATS
    LDAA [G_X]
    LDAB [G_Y]
    JSR CELL
    ANDA 127
    CLR [G_CONTEXT]
    CMPA 3
    BNE MENU_PLAIN
MENU_CONTEXT:
    INC [G_CONTEXT]
    LDX MAIN_NAMES
    LDAA 8
    BRA MENU_DRAW
MENU_PLAIN:
    LDX MAIN_NAMES + 2
    LDAA 7
MENU_DRAW:
    STX [UI_PTR]
    STAA [COUNT]
    LDAA 1
    STAA [UI_ROW]
    JSR RENDER_CHOICES
    LDX S_MENU_KEYS
    LDAB ((FRAMEBUFFER + 704) & 255)
    LDAA ((FRAMEBUFFER + 704) >> 8)
    JMP TEXT
RENDER_BAG:
    JSR RENDER_STATS
    LDAA 1
    STAA [UI_ROW]
    CLR [G_SLOT]
BAG_DRAW_LOOP:
    JSR BAG_ITEM
    JSR ITEM_NAME
    LDAA [UI_ROW]
    LDAB 64
    JSR MULTIPLY
    ADDB ((FRAMEBUFFER + 3) & 255)
    ADCA ((FRAMEBUFFER + 3) >> 8)
    JSR TEXT
    LDAA [G_SLOT]
    CMPA [G_MENU]
    BNE BAG_DRAW_NEXT
    JSR DRAW_SELECTION
BAG_DRAW_NEXT:
    INC [UI_ROW]
    INC [G_SLOT]
    LDAA [G_SLOT]
    CMPA 6
    BNE BAG_DRAW_LOOP
    LDX S_BACK
    LDAB ((FRAMEBUFFER + 451) & 255)
    LDAA ((FRAMEBUFFER + 451) >> 8)
    JSR TEXT
    LDAA [G_MENU]
    CMPA 6
    BNE BAG_NO_BACK_CURSOR
    JSR DRAW_SELECTION
BAG_NO_BACK_CURSOR:
    LDX S_MENU_KEYS
    LDAB ((FRAMEBUFFER + 704) & 255)
    LDAA ((FRAMEBUFFER + 704) >> 8)
    JMP TEXT
ITEM_NAME:
    CMPA 17
    BCS ITEM_NAME_BELOW_17
    JMP ITEM_NAME_RAW
ITEM_NAME_BELOW_17:
    CMPA 2
    BCC ITEM_NAME_AT_LEAST_2
    JMP ITEM_NAME_RAW
ITEM_NAME_AT_LEAST_2:
    CMPA 14
    BCC ITEM_NAME_MAGIC
    CMPA 7
    BCS ITEM_NAME_MAGIC
    JMP ITEM_NAME_RAW
ITEM_NAME_MAGIC:
    STAA [ITEM_TYPE]
    JSR MAGIC_INDEX
    LDX BITS
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    LDAA [G_KNOWN]
    BITA [X]
    BEQ ITEM_NAME_UNKNOWN
    LDX G_IDENTITIES
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    LDAB [X]
    ASLB
    LDX EFFECT_NAMES
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    JMP LOAD_STRING
ITEM_NAME_UNKNOWN:
    LDAA [ITEM_TYPE]
ITEM_NAME_RAW:
    TAB
    ASLB
    LDX ITEM_NAMES
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    JMP LOAD_STRING
RENDER_ITEM:
    JSR BAG_ITEM
    JSR ITEM_NAME
    LDAB ((FRAMEBUFFER + 64) & 255)
    LDAA ((FRAMEBUFFER + 64) >> 8)
    JSR TEXT
    LDAA [ITEM_TYPE]
    CMPA 14
    BCC ITEM_NO_COMPARISON
    CMPA 7
    BCS ITEM_NO_COMPARISON
    CMPA 10
    BCC ARMOR_COMPARISON
    LDX S_ATK_SWAP
    LDAB ((FRAMEBUFFER + 128) & 255)
    LDAA ((FRAMEBUFFER + 128) >> 8)
    JSR TEXT
    LDAA [G_ATTACK]
    LDX FRAMEBUFFER + 137
    JSR NUMBER
    LDAA [ITEM_TYPE]
    SUBA 3
    BRA COMPARISON_VALUE
ARMOR_COMPARISON:
    LDX S_DEF_SWAP
    LDAB ((FRAMEBUFFER + 128) & 255)
    LDAA ((FRAMEBUFFER + 128) >> 8)
    JSR TEXT
    LDAA [G_DEFENSE]
    LDX FRAMEBUFFER + 137
    JSR NUMBER
    LDAA [ITEM_TYPE]
    SUBA 9
COMPARISON_VALUE:
    LDX FRAMEBUFFER + 147
    JSR NUMBER
ITEM_NO_COMPARISON:
    LDX ITEM_ACTIONS
    STX [UI_PTR]
    LDAA 3
    STAA [COUNT]
    LDAA 4
    STAA [UI_ROW]
    JSR RENDER_CHOICES
    JMP RENDER_MESSAGE
RENDER_CHOICES:
    CLR [CANDIDATE]
CHOICES_NEXT:
    LDAA [CANDIDATE]
    CMPA [G_MENU]
    BNE CHOICES_UNSELECTED
    JSR DRAW_SELECTION
CHOICES_UNSELECTED:
    JSR RENDER_LINE
    INC [CANDIDATE]
    DEC [COUNT]
    BNE CHOICES_NEXT
    RTS
RENDER_LINES:
    JSR RENDER_LINE
    DEC [COUNT]
    BNE RENDER_LINES
    RTS
RENDER_LINE:
    LDX [UI_PTR]
    JSR LOAD_STRING
    LDAA [UI_ROW]
    LDAB 64
    JSR MULTIPLY
    ADDB ((FRAMEBUFFER + 3) & 255)
    ADCA ((FRAMEBUFFER + 3) >> 8)
    JSR TEXT
    LDX [UI_PTR]
    INX
    INX
    STX [UI_PTR]
    INC [UI_ROW]
    RTS
DRAW_SELECTION:
    LDAA [UI_ROW]
    LDAB 64
    JSR MULTIPLY
    ADDB ((FRAMEBUFFER + 0) & 255)
    ADCA ((FRAMEBUFFER + 0) >> 8)
    STAB [P2 + 1]
    STAA [P2]
    LDX [P2]
    LDAA 0x3E
    JSR GLYPH
    RTS
RENDER_INSPECT:
    LDAA [G_INSPECT_X]
    STAA [NX]
    LDAA [G_INSPECT_Y]
    STAA [NY]
    LDAA [NY]
    SUBA [VIEW_Y]
    CMPA 20
    BCC INSPECT_NAME
    JSR TILE_DESTINATION
    LDX [DRAW]
    LDAA 0x3E
    JSR GLYPH
INSPECT_NAME:
    JSR FIND_ENEMY
    TSTA
    BEQ INSPECT_ITEM
    DECA
    ASLA
    STAA [CANDIDATE]
    TAB
    LDX ENEMY_NAMES
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    JSR LOAD_STRING
    LDAB ((FRAMEBUFFER + 704) & 255)
    LDAA ((FRAMEBUFFER + 704) >> 8)
    JSR TEXT
    LDX [E_PTR]
    LDAA [X + 3]
    LDX FRAMEBUFFER + 720
    JSR NUMBER
    LDX FRAMEBUFFER + 0
    LDAA JR200_CHAR_SPACE
INSPECT_CLEAR_HUD:
    STAA [X]
    INX
    CPX FRAMEBUFFER + 64
    BNE INSPECT_CLEAR_HUD
    LDAB [CANDIDATE]
    LDX ENEMY_TRAITS
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    JSR LOAD_STRING
    LDAB ((FRAMEBUFFER + 0) & 255)
    LDAA ((FRAMEBUFFER + 0) >> 8)
    JMP TEXT
INSPECT_ITEM:
    TST [G_WAND_SLOT]
    BEQ INSPECT_GROUND_ITEM
    LDAA [NX]
    CMPA [G_X]
    BNE INSPECT_GROUND_ITEM
    LDAA [NY]
    CMPA [G_Y]
    BNE INSPECT_GROUND_ITEM
    LDX S_BACK
    BRA INSPECT_TEXT
INSPECT_GROUND_ITEM:
    JSR FIND_ITEM
    TSTA
    BEQ INSPECT_TERRAIN
    JSR ITEM_NAME
    BRA INSPECT_TEXT
INSPECT_TERRAIN:
    LDAA [NX]
    LDAB [NY]
    JSR CELL
    ANDA 127
    CMPA 5
    BNE INSPECT_TILE_TYPE
    CLRA
INSPECT_TILE_TYPE:
    ASLA
    TAB
    LDX TERRAIN_NAMES
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    JSR LOAD_STRING
INSPECT_TEXT:
    LDAB ((FRAMEBUFFER + 704) & 255)
    LDAA ((FRAMEBUFFER + 704) >> 8)
    JMP TEXT
RENDER_STATS:
    LDX S_STATS
    LDAB ((FRAMEBUFFER + 0) & 255)
    LDAA ((FRAMEBUFFER + 0) >> 8)
    JSR TEXT
    LDAA [G_ATTACK]
    LDX FRAMEBUFFER + 4
    JSR NUMBER
    LDAA [G_DEFENSE]
    LDX FRAMEBUFFER + 12
    JSR NUMBER
    LDX FRAMEBUFFER + 23
RENDER_GOLD:
    STX [NUM_DEST]
    LDAB [G_GOLD + 1]
    LDAA [G_GOLD]
    STAB [GOLD_VALUE + 1]
    STAA [GOLD_VALUE]
    LDAB ((10000) & 255)
    LDAA ((10000) >> 8)
    JSR GOLD_DIGIT
    LDAB ((1000) & 255)
    LDAA ((1000) >> 8)
    JSR GOLD_DIGIT
    LDAA 48
    STAA [DIGIT]
GOLD_HUNDREDS:
    LDAB [GOLD_VALUE + 1]
    LDAA [GOLD_VALUE]
    SUBB ((100) & 255)
    SBCA ((100) >> 8)
    BCS GOLD_REMAINDER
    STAB [GOLD_VALUE + 1]
    STAA [GOLD_VALUE]
    INC [DIGIT]
    BRA GOLD_HUNDREDS
GOLD_REMAINDER:
    ADDB ((100) & 255)
    ADCA ((100) >> 8)
    STAB [NUM]
    JMP NUMBER_HUNDREDS_DONE
GOLD_DIGIT:
    STAB [GOLD_DIVISOR + 1]
    STAA [GOLD_DIVISOR]
    LDAA 48
    STAA [DIGIT]
GOLD_DIGIT_LOOP:
    LDAB [GOLD_VALUE + 1]
    LDAA [GOLD_VALUE]
    SUBB [GOLD_DIVISOR + 1]
    SBCA [GOLD_DIVISOR]
    BCS GOLD_DIGIT_DONE
    STAB [GOLD_VALUE + 1]
    STAA [GOLD_VALUE]
    INC [DIGIT]
    BRA GOLD_DIGIT_LOOP
GOLD_DIGIT_DONE:
    LDX [NUM_DEST]
    LDAA [DIGIT]
    JSR GLYPH
    LDX [NUM_DEST]
    INX
    STX [NUM_DEST]
    RTS

