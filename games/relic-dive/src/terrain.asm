    LDX ROOM_CX
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    LDAA [X]
    STAA [NX]
    LDX ROOM_CY
    STAB [INDEX_OFFSET + 1]
    ADDX16 INDEX_OFFSET
    LDAA [X]
    STAA [NY]
    JSR RANDOM
    ANDA 1
    BEQ TERRAIN_HORIZONTAL_FIRST
    JSR TERRAIN_VERTICAL
    JMP TERRAIN_HORIZONTAL
TERRAIN_HORIZONTAL_FIRST:
    JSR TERRAIN_HORIZONTAL
    JMP TERRAIN_VERTICAL
TERRAIN_HORIZONTAL:
    JSR TERRAIN_DOT
    LDAA [GX]
    CMPA [NX]
    BEQ TERRAIN_AXIS_DONE
    BHI TERRAIN_LEFT
    INC [GX]
    BRA TERRAIN_HORIZONTAL
TERRAIN_LEFT:
    DEC [GX]
    BRA TERRAIN_HORIZONTAL
TERRAIN_VERTICAL:
    JSR TERRAIN_DOT
    LDAA [GY]
    CMPA [NY]
    BEQ TERRAIN_AXIS_DONE
    BHI TERRAIN_UP
    INC [GY]
    BRA TERRAIN_VERTICAL
TERRAIN_UP:
    DEC [GY]
    BRA TERRAIN_VERTICAL
TERRAIN_AXIS_DONE:
    RTS
TERRAIN_DOT:
    LDAA [GX]
    LDAB [GY]
    JSR CELL
    LDAA 1
    JSR WRITE_CELL
    RTS
