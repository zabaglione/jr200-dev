    LDAA [NY]
    STAA [G_Y]
    JSR TRIGGER_TRAP
    JSR PICKUP
    LDAA [G_MODE]
    CMPA 9
    BEQ PLAYER_WON
    LDAA [G_KEY]
    CMPA 4
    BHI PLAYER_WON
    LDAA 1
    STAA [G_AUTOWALK]
PLAYER_WON:
    JMP COMMIT_TURN
WALKABLE:
    LDAA [NX]
    CMPA MAP_WIDTH
    BCC NOT_WALKABLE
    LDAB [NY]
    CMPB MAP_HEIGHT
    BCC NOT_WALKABLE
    JSR CELL
    ANDA 127
    CMPA 5
    BEQ NOT_WALKABLE
    TSTA
    RTS
NOT_WALKABLE:
    CLRA
    RTS
COMMIT_TURN:
    LDAB [G_TURNS + 1]
    LDAA [G_TURNS]
    ADDB ((1) & 255)
    ADCA ((1) >> 8)
    STAB [G_TURNS + 1]
    STAA [G_TURNS]
    LDAA [G_MODE]
    CMPA 9
    BNE TURN_CONTINUES
    CLR [G_AUTOWALK]
    RTS
TURN_CONTINUES:
    TST [G_HP]
    BNE TURN_PLAYER_ALIVE
    JMP TURN_DIE
TURN_PLAYER_ALIVE:
    TST [G_BUFF]
    BEQ TURN_FOOD
    DEC [G_BUFF]
TURN_FOOD:
    TST [G_POISON]
    BEQ POISON_TICK_DONE
    DEC [G_POISON]
    INC [G_POISON_TICK]
    LDAA [G_POISON_TICK]
    ANDA 1
    BNE POISON_TICK_DONE
    TST [G_HP]
    BEQ POISON_TICK_DONE
    DEC [G_HP]
    LDAA 16
    STAA [G_MESSAGE]
POISON_TICK_DONE:
    TST [G_HP]
    BNE POISON_SURVIVED
    JMP TURN_DIE
POISON_SURVIVED:
    TST [G_FOOD]
    BEQ STARVING
    LDAA [G_TURNS + 1]
    ANDA 1
    BEQ FOOD_CONSUME
    LDX G_BAG
FOOD_RING_SCAN:
    LDAA [X]
    CMPA 22
    BEQ FOOD_SKIP
    INX
    CPX G_BAG + 6
    BNE FOOD_RING_SCAN
FOOD_CONSUME:
    DEC [G_FOOD]
FOOD_SKIP:
    CLR [G_STARVE]
    INC [G_REGEN]
    LDAA [G_REGEN]
    CMPA 12
    BCS TURN_ENEMIES
    CLR [G_REGEN]
    LDAA [G_HP]
    CMPA [G_MAX_HP]
    BCC TURN_ENEMIES
    INC [G_HP]
    BRA TURN_ENEMIES
STARVING:
    CLR [G_REGEN]
    INC [G_STARVE]
    LDAA [G_STARVE]
    ANDA 1
    BNE TURN_ENEMIES
    TST [G_HP]
    BEQ TURN_ENEMIES
    DEC [G_HP]
TURN_ENEMIES:
    LDAA [G_MODE]
    CMPA 9
    BNE TURN_NOT_WON
    CLR [G_AUTOWALK]
    RTS
TURN_NOT_WON:
    JSR ENSURE_VISIBILITY
    TST [NEW_SIGHT]
    BEQ NO_NEW_SIGHT
    CLR [G_AUTOWALK]
NO_NEW_SIGHT:
    JSR ENEMIES_TURN
    TST [G_HP]
    BNE TURN_ALIVE
TURN_DIE:
    CLR [G_SUSPEND]
    CLR [G_AUTOWALK]
    LDAA 8
    STAA [G_MODE]
TURN_ALIVE:
    LDAA [G_FOOD]
    CMPA 40
    BHI TURN_DONE
    CLR [G_AUTOWALK]
    TST [G_MESSAGE]
    BNE TURN_DONE
    LDAA 5
    STAA [G_MESSAGE]
TURN_DONE:
    RTS
ENEMIES_TURN:
    JSR POLL_KEY
    CLR [E_INDEX]
ENEMY_TURN_LOOP:
    TST [G_HP]
    BNE ENEMY_PLAYER_ALIVE
    RTS
ENEMY_PLAYER_ALIVE:
    JSR ENEMY_POINTER
    TST [X + 3]
    BNE ENEMY_ACTIVE
    JMP ENEMY_TURN_NEXT
ENEMY_ACTIVE:
    TST [X + 7]
    BEQ ENEMY_RELEASED
    DEC [X + 7]
    JMP ENEMY_TURN_NEXT
ENEMY_RELEASED:
    LDAA [X + 2]
    STAA [ENEMY_KIND]
    CMPA 8
    BNE ENEMY_NO_REGEN
    LDAA [G_TURNS + 1]
    ANDA 3
    BNE ENEMY_NO_REGEN
    LDAA [X + 3]
    CMPA 12
    BCC ENEMY_NO_REGEN
    INC [X + 3]
ENEMY_NO_REGEN:
    LDAA [ENEMY_KIND]
    CMPA 1
    BNE ENEMY_AWAKE
    LDAA [G_TURNS + 1]
    ANDA 1
    BEQ ENEMY_AWAKE
    JMP ENEMY_TURN_NEXT
ENEMY_AWAKE:
    LDAA [X]
    LDAB [X + 1]
    JSR VISIBLE_CELL
    TST [X]
    BEQ ENEMY_MEMORY
    LDAA [ENEMY_KIND]
    CMPA 14
    BEQ ENEMY_RANGED
    CMPA 12
    BNE ENEMY_NOT_RANGED
ENEMY_RANGED:
    JSR ENEMY_POINTER
    LDAA [X]
    CMPA [G_X]
    BEQ ENEMY_SHOOT
    LDAA [X + 1]
    CMPA [G_Y]
    BNE ENEMY_NOT_RANGED
