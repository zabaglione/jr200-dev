    JSR ENEMY_STRIKE
    LDAA [ENEMY_KIND]
    CMPA 14
    BNE ENEMY_ARROW_MESSAGE
    LDAA 31
    BRA ENEMY_RANGED_MESSAGE
ENEMY_ARROW_MESSAGE:
    LDAA 15
ENEMY_RANGED_MESSAGE:
    STAA [G_MESSAGE]
    JMP ENEMY_TURN_NEXT
ENEMY_NOT_RANGED:
    JSR ENEMY_POINTER
    LDAA [G_X]
    STAA [X + 4]
    LDAA [G_Y]
    STAA [X + 5]
ENEMY_MEMORY:
    JSR ENEMY_POINTER
    LDAA [X + 4]
    CMPA 255
    BNE ENEMY_HAS_TARGET
    JMP ENEMY_TURN_NEXT
ENEMY_HAS_TARGET:
