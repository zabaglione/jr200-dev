    def init(self):
        self.d = list(LEVELS_DATA[self.port.level])
        self.b = self.d[:64]
        for i in range(64):
            self.c[64 + i] = i
        self.c[self.d[64]] = 1
        self.c[self.d[65]] = 1
        self.par = self.d[69]

    def spend_move(self):
        if self.moves < 255:
            self.moves += 1
        else:
            self.overflow = 1

    def take_rune(self, pos):
        if pos == self.d[67]:
            self.runes |= 1
        if pos == self.d[68]:
            self.runes |= 2

    def act(self, action):
        self.frames = 0
        self.sounds = []
        if action >= 5:
            return
        c = self.c
        changed = 0
        for _ in range(6):
            moved = 0
            for k in range(64):
                i = 63 - k if action in (2, 4) else k
                if c[i]:
                    n = move(i, action)
                    if self.b[n] != 1 and not c[n]:
                        c[n] = 1
                        c[64 + n] = i
                        c[i] = 0
                        changed = moved = 1
                        self.take_rune(n)
            if moved:
                self.sounds.append(0)
                self.frames += 2
                for i in range(64):
                    c[64 + i] = i
        if changed:
            self.spend_move()
            self.sounds.append(1)
        self.filled = sum(1 for i in range(64) if c[i] and self.b[i] == 3)
        if self.filled == 2:
            self.port.rank_clear()

    def state_bytes(self):
        return bytes([getattr(self, n) for n in FIELDS] + self.b + self.c).hex()
