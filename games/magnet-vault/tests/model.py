def move(pos, action):
    if action == 1 and pos >= 8:
        return pos - 8
    if action == 2 and pos < 56:
        return pos + 8
    if action == 3 and pos % 8:
        return pos - 1
    if action == 4 and pos % 8 < 7:
        return pos + 1
    return pos


class MagnetVault:
    port = None

    def __init__(self):
        self.reset()

    def reset(self):
        for name in FIELDS:
            setattr(self, name, 0)
        self.b = [0] * 64
        self.c = [0] * 64
        self.d = [0] * 70
        self.frames = 0

    def init(self):
        self.d = list(LEVELS_DATA[self.port.level])
        self.b = self.d[:64]
        self.pos = self.origin = self.d[64]
        self.facing = 4
        self.c[self.d[65]] = 1
        self.c[self.d[66]] = 1
        self.par = self.d[69]

    def spend_move(self):
        if self.moves < 255:
            self.moves += 1
        else:
            self.overflow = 1

    def take_rune(self, pos):
        if pos == self.d[67]:
            self.runes |= 1
        if pos == self.d[68]:
            self.runes |= 2

    def act(self, action):
        self.frames = 0
        before, facing = self.pos, self.facing
        if action < 5:
            self.facing = action
            target = move(self.pos, action)
            if self.b[target] != 1 and self.c[target] == 0:
                self.pos = target
        if action == 5:
            front = move(self.pos, self.facing)
            behind = move(self.pos, OPPOSITE[self.facing])
            if self.c[front] and not self.c[behind] and self.b[behind] != 1:
                self.c[front] = 0
                self.c[self.pos] = 1
                self.pulling = 1
                self.block_origin = front
                self.pos = behind
                if self.pulls < 255:
                    self.pulls += 1
        if self.pos != before:
            self.frames += 2
            self.origin = self.pos
            self.pulling = 0
        if self.pos != before or self.facing != facing:
            self.spend_move()
            self.take_rune(self.pos)
        if sum(1 for i in range(64) if self.b[i] == 3 and self.c[i]) == 2:
            self.port.rank_clear()

    def state_bytes(self):
        return bytes([getattr(self, n) for n in FIELDS] + self.b + self.c).hex()
